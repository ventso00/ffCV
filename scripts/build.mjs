import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const read=p=>readFile(new URL(p,root),'utf8');
const assets={};
for(const [name,type] of [['card-background.webp','image/webp'],['concept-cutout.webp','image/webp'],['icon-192.png','image/png'],['icon-512.png','image/png']]) assets['/'+name]={base64:(await readFile(new URL('assets/'+name,root))).toString('base64'),type};
const source='const page='+JSON.stringify(await read('page.html'))+';\nconst app='+JSON.stringify(await read('app.js'))+';\nconst css='+JSON.stringify(await read('style.css'))+';\nconst model='+JSON.stringify(await read('profile-model.js'))+';\nconst assets='+JSON.stringify(assets)+';\n'+(await read('profile-model.js')).replaceAll('export ','')+'\n'+await read('server.js');
await mkdir(new URL('worker/',root),{recursive:true});
await mkdir(new URL('dist/server/',root),{recursive:true});
await mkdir(new URL('dist/.openai/',root),{recursive:true});
await writeFile(new URL('worker/index.js',root),source);
await writeFile(new URL('dist/server/index.js',root),source);
await copyFile(new URL('.openai/hosting.json',root),new URL('dist/.openai/hosting.json',root));
console.log('Worker assembled and artifact built.');
